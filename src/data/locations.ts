export function applyEmergency(locations: FoodLocation[]): FoodLocation[] {
  const updated = locations.map((loc) => {
    if (loc.id === 'loc-e') {
      return {
        ...loc,
        isOpenToday: false,
        status: 'closed' as const,
        waitMinutes: 0,
        notes: 'Closed unexpectedly for the rest of today.',
      }
    }
    if (loc.id === 'loc-b') {
      return {
        ...loc,
        waitMinutes: 60,
        currentLoad: Math.min(1, loc.currentLoad + 0.35),
        notes: 'Higher demand after a nearby location closed.',
      }
    }
    if (loc.id === 'loc-c') {
      return {
        ...loc,
        waitMinutes: Math.max(8, loc.waitMinutes - 2),
        inventory: loc.inventory.map((i) => ({ ...i, status: 'available' as const })),
        notes: 'Just received a new food shipment.',
      }
    }
    return loc
  })
  if (!updated.some((l) => l.id === 'loc-d')) {
    updated.push(EMERGENCY_LOCATION_D)
  }
  return updated
}
